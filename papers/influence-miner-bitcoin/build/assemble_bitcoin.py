"""Assemble the Bitcoin paper from the Python full paper (shared, project-independent
sections) and the Bitcoin-specific blocks in this folder."""
import io
import os
import re

S = os.path.dirname(os.path.abspath(__file__))
PY = os.path.join(os.path.dirname(os.path.dirname(S)), 'influence-miner', 'influence-miner-acm-full.tex')
OUT = os.path.join(os.path.dirname(S), 'influence-miner-bitcoin.tex')


def rd(name):
    return io.open(os.path.join(S, name), encoding='utf-8').read()


py = io.open(PY, encoding='utf-8').read()


def between(start, end):
    a = py.index(start)
    b = py.index(end, a)
    return py[a:b]


# ---- preamble up to \begin{abstract} ----
pre = py[:py.index('\\begin{abstract}')]
pre = pre.replace('%% Influence Miner paper - FULL-LENGTH version (ACM acmart format, no page limit).',
                  '%% Influence Miner for Bitcoin - full-length version (ACM acmart format). Generated by build/assemble_bitcoin.py.')
pre = re.sub(r'\\title\[Influence Miner\]\{[^\n]*\}',
             r'\\title[Influence Miner for Bitcoin]{Influence Miner for Bitcoin: How Influence Is Exercised in Bitcoin Improvement Proposal Discussions, 2011--2026}', pre)
pre = pre.replace('\\keywords{open source software, decision-making, influence mining, governance, Python Enhancement Proposals, Bitcoin Improvement Proposals, mailing lists, software repository mining}',
                  '\\keywords{Bitcoin, Bitcoin Improvement Proposals, open source governance, decision-making, influence mining, mailing lists, software repository mining}')
pre = pre.replace('\\usepackage{pgfplots}', '\\usepackage{pgfplots}\n\\usepackage{tikz}')

parts = [pre]
parts.append(rd('block_abstract.tex'))
parts.append(py[py.index('\\end{abstract}') + len('\\end{abstract}'):py.index('\\section{Introduction}')])   # CCS + keywords + maketitle
parts.append(rd('block_intro.tex'))
parts.append(rd('block_background.tex'))
parts.append(rd('block_rqs.tex'))
# shared: conceptualisation + taxonomy (Python examples are kept; they are illustrations of the categories)
tax = between('\\section{Conceptualising Influence in OSS Decision-Making}', '\\section{Influence Miner: Implementation}')
tax = tax.replace('Table~\\ref{tab:samples} in Section~\\ref{sec:results} shows two sentences per mechanism as extracted by the tool.',
                  'Table~\\ref{tab:samples} in Section~\\ref{sec:results} shows two Bitcoin sentences per mechanism as extracted by the tool.')
parts.append(tax)
# shared: implementation (without the Python tool-interface figures), plus the Bitcoin adaptation
impl = between('\\section{Influence Miner: Implementation}', '\\subsection{Tool Interfaces}')
parts.append(impl)
parts.append(rd('block_adaptation.tex'))
parts.append(rd('block_corpus.tex'))
parts.append(rd('block_timeline_ext.tex'))
parts.append(rd('block_results.tex'))
parts.append(rd('block_rq6.tex'))
parts.append(rd('block_icis.tex'))
parts.append(rd('block_compare.tex'))
parts.append(rd('block_discussion.tex'))
# shared appendix on detector rules, with the Bitcoin cue additions
app = between('\\appendix', '\\begin{thebibliography}{00}')
app = app.replace('\\emph{procedure, belongs on, the archives, drop it, please stop} only near a process, list or thread word.',
                  '\\emph{procedure, belongs on, the archives, drop it, please stop} only near a process, list or thread word. For Bitcoin the lists were extended with the vocabulary of its governance: \\emph{lead maintainer, core maintainer(s), BIP editors, wladimir, gavin, gmaxwell, sipa} (authority); the companies and funders active in the project---\\emph{at Blockstream/Chaincode/Coinbase/Bitmain/BitPay/Square/Spiral/Brink/MIT DCI/Lightning Labs}, \\emph{pays my salary, grant from, OpenSats}---(corporate interest); \\emph{fork bitcoin, contentious hard fork, split the chain, run Bitcoin XT/Classic/Unlimited, leave bitcoin, sell my coins} (exit threat); \\emph{censored, censoring, banned from the list, moderation queue, list moderators, this is bitcoin-dev, not} (procedural control); and \\emph{shill, scam, sockpuppet, brigading, concern troll, bad faith, dishonest, disingenuous} (incivility).')
parts.append(app)
# bibliography: Python paper's entries plus the Bitcoin ones, plus a self-citation of the Python paper
bib = py[py.index('\\begin{thebibliography}{00}'):]
bib = bib.replace('\\bibitem{ossGovernance}', rd('block_bib_bitcoin.tex').lstrip('\n') + '''
\\bibitem{influenceMinerPython}
Pankaj Sharma. 2026. Influence Miner: Mining strategic, operational, functional, and external influence in open source software decision-making. Draft manuscript, September 2026.

\\bibitem{ossGovernance}''')
parts.append(bib)

s = ''.join(parts)

# the two timelines: fill the yearly controversial shares
years = rd('data_contro_years.txt').strip()
s = s.replace('%%CONTRO_YEARS%%', years)
s = s.replace('%%CONTRO_PCT%%', rd('data_contro_pct.txt').strip())

io.open(OUT, 'w', encoding='utf-8', newline='\n').write(s)
print('written', OUT, len(s))
